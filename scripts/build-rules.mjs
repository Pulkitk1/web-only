// Builds the staged Firestore rule sets from shared pieces, so Part A, Part B and the combined set cannot drift apart:
//
//   node scripts/build-rules.mjs          writes   firebase/firestore.rules        PART A  (wallet integrity: the production deployment candidate)
//                                                  firebase/rules/part-b.rules     PART B  (habit and document validation: NOT a candidate yet)
//                                                  firebase/rules/combined.rules   A + B   (the eventual end state)
//   node scripts/build-rules.mjs --check  fails (exit 1) if a committed file differs from what the pieces produce (used by tests/rulesBuild.test.ts)
//
// The rules in force are `android/firestore.rules`; every set below is those rules plus ONLY the changes of its part, so each part can be
// published alone. Firestore rules have no include mechanism, which is why the three complete files are generated.
//
//   PART A  changes only what a NEW write must look like, or the keys an update CHANGES. It never re-validates an existing habit,
//           completion or note, so historical habit data cannot make an unrelated update fail.
//   PART B  adds field validation of habits, completions and notes. These re-validate the WHOLE resulting document on every update, which
//           is why B waits for an inspection of the real data (RULES_CONSOLE_INSPECTION.md).
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const HEADERS = {
  a: `// PART A: WALLET INTEGRITY. A PROPOSED rule set: NOT PUBLISHED. The rules in force are \`android/firestore.rules\`; this is those rules plus only
// the wallet changes below. It is the production deployment candidate. It is generated by scripts/build-rules.mjs; edit that, not this file.
//
// What Part A changes (each only judges a NEW write, or the keys an update CHANGES; it never re-validates a stored habit, completion or note):
//   - ledger entries: a known type with its id pattern and amounts (daily +1, milestones 5/10/20, purchase EXACTLY -20 coins, freeze removal -1)
//   - reward records, freeze records, monthly counters: known fields, valid values, the counter going up by exactly one with each freeze
//   - the profile: only wallet and plain profile fields may change; the transaction pointer cannot move alone; a new profile has exactly Android's fields
//   - paths: nothing may be created below a habit except \`completions\`; \`todos\` can no longer be written (still readable and deletable)
// What it does NOT do: prove a reward was earned; enforce the 3-day freeze window (Android's guest import replays old freeze dates through
// the same writes, so a date window would break it); stop the owner from setting \`deletionRequested\` (Android's account deletion does that
// from the client). See CLOUD_FUNCTIONS_PROPOSAL.md.`,
  b: `// PART B: HABIT AND DOCUMENT VALIDATION. A PROPOSED rule set: NOT PUBLISHED and NOT a deployment candidate yet. The rules in force are
// \`android/firestore.rules\`; this is those rules plus only the validation below (the wallet rules are left exactly as in force). It is
// generated by scripts/build-rules.mjs; edit that, not this file.
//
// Part B re-validates the WHOLE resulting document on every habit, completion and note write, so a stored document that breaks a bound would
// make Android's next check-in, edit or reorder of it fail. Do not publish it until the real data has been inspected (RULES_CONSOLE_INSPECTION.md).
// Rules cannot count documents, so there is no limit on how many habits an account may hold here (the Web app enforces 200).`,
  ab: `// PARTS A + B COMBINED: the intended final Firestore ruleset for Consisto. Part A (wallet integrity) is the existing production baseline and is
// already published; this file contains Part A plus Part B (habit, completion and calendar-note validation). It must not be published until that is
// explicitly approved. Generated by scripts/build-rules.mjs; edit that, not this file.`,
};

export function buildRules({ a, b, feedback = false }) {
  const head = HEADERS[a && b ? 'ab' : a ? 'a' : 'b'];
  // Feedback is NOT granted by any staged set (Phase 11C.4 decision): production has no `feedback` rule today, so it stays denied by default.
  // Set `feedback: true` only to re-enable the create-only rule that `android/firestore.rules` holds.
  const feedbackSection = feedback
    ? `    // Feedback & Suggestions: create-only (the same rule as android/firestore.rules).
    match /feedback/{feedbackId} {
      allow get: if request.auth != null && (resource == null || resource.data.userId == request.auth.uid);
      allow create: if request.auth != null
        && request.resource.data.keys().hasOnly(['category', 'description', 'userId', 'isGuest', 'createdAt', 'appVersion', 'status'])
        && request.resource.data.keys().hasAll(['category', 'description', 'userId', 'isGuest', 'createdAt', 'appVersion', 'status'])
        && request.resource.data.userId == request.auth.uid
        && request.resource.data.category in ['bug', 'improvement', 'feature']
        && request.resource.data.description is string
        && request.resource.data.description.size() <= 2000
        && request.resource.data.description.trim().size() > 0
        && request.resource.data.isGuest is bool
        && request.resource.data.isGuest == (request.auth.token.firebase.sign_in_provider == 'anonymous')
        && request.resource.data.createdAt == request.time
        && request.resource.data.appVersion is string
        && request.resource.data.appVersion.size() <= 32
        && request.resource.data.status == 'new';
      allow list, update, delete: if false;
    }
`
    : `    // Feedback & Suggestions: NOT granted here (no rule: denied by default). Enabling it is a separate decision.
`;


  // ── users: profile and wallet fields ──────────────────────────────────────────────────────────────────────────────────
  const usersHelpers = `      function isOwner() { return request.auth != null && request.auth.uid == userId; }
      function userPath() { return /databases/$(database)/documents/users/$(userId); }
      function txPath(id) { return /databases/$(database)/documents/users/$(userId)/walletTransactions/$(id); }${
        a
          ? `
      function freezePath(id) { return /databases/$(database)/documents/users/$(userId)/freezes/$(id); }
      function monthPath(m) { return /databases/$(database)/documents/users/$(userId)/freezeMonths/$(m); }`
          : ''
      }

      // Wallet fields (coins, freezesOwned) may only change together with a new ledger entry written in the
      // same transaction whose deltas and balance match the change.
      function walletUnchanged() {
        return request.resource.data.get('coins', 0) == resource.data.get('coins', 0)
          && request.resource.data.get('freezesOwned', 0) == resource.data.get('freezesOwned', 0)
          && request.resource.data.get('pendingAdjustment', 0) == resource.data.get('pendingAdjustment', 0)${
            a
              ? `
          // Every legitimate ledger entry changes at least one wallet field, so the pointer may not move on its own.
          && request.resource.data.get('lastTransactionId', '') == resource.data.get('lastTransactionId', '')`
              : ''
          };
      }
      function deleting() { return get(userPath()).data.get('deletionRequested', false) == true; }
      function walletChangeBackedByLedger() {
        let id = request.resource.data.lastTransactionId;
        let tx = getAfter(txPath(id)).data;
        return resource.data.get('deletionRequested', false) != true
          && id != resource.data.get('lastTransactionId', '')
          && !exists(txPath(id))
          && tx.coinDelta == request.resource.data.coins - resource.data.get('coins', 0)
          && tx.freezeDelta == request.resource.data.freezesOwned - resource.data.get('freezesOwned', 0)
          && tx.balanceAfter == request.resource.data.coins
          && tx.get('pendingDelta', 0) == request.resource.data.get('pendingAdjustment', 0) - resource.data.get('pendingAdjustment', 0)
          && request.resource.data.coins >= 0
          && request.resource.data.freezesOwned >= 0
          && request.resource.data.get('pendingAdjustment', 0) >= 0;
      }${
        a
          ? `
      // The only fields an update may touch: the wallet fields (always together with a ledger entry), the welcome-freeze marker, the
      // deletion marker Android's account deletion writes, and the plain profile fields. Judged on the CHANGED keys, so an old profile with
      // other fields is unaffected.
      function profileUpdateOk() {
        return request.resource.data.diff(resource.data).affectedKeys().hasOnly([
          'coins', 'freezesOwned', 'pendingAdjustment', 'lastTransactionId', 'updatedAt',
          'welcomeFreezePending', 'deletionRequested', 'deletionRequestedAt', 'displayName', 'email', 'isDark'
        ]);
      }
      // A new profile is exactly Android's: 20 coins, no freezes, and only these fields (Android's loadUser, the guest migration and the Web import all qualify).
      function profileCreateOk() {
        return request.resource.data.keys().hasOnly([
            'email', 'displayName', 'coins', 'freezesOwned', 'welcomeFreezePending', 'isDark', 'createdAt', 'updatedAt'
          ])
          && request.resource.data.get('coins', 0) == 20
          && request.resource.data.get('freezesOwned', 0) == 0;
      }`
          : ''
      }

      allow read: if isOwner();
${
  a
    ? `      allow create: if isOwner() && profileCreateOk();
      // Once account deletion has started, the flag can't be cleared (so ledger records can't be deleted and restored).
      allow update: if isOwner() && profileUpdateOk() && (walletUnchanged() || walletChangeBackedByLedger())
        && !(resource.data.get('deletionRequested', false) == true && request.resource.data.get('deletionRequested', false) != true)
        && request.resource.data.get('deletionRequested', false) is bool;`
    : `      allow create: if isOwner() && request.resource.data.get('coins', 0) == 20 && request.resource.data.get('freezesOwned', 0) == 0;
      // Once account deletion has started, the flag can't be cleared (so ledger records can't be deleted and restored).
      allow update: if isOwner() && (walletUnchanged() || walletChangeBackedByLedger())
        && !(resource.data.get('deletionRequested', false) == true && request.resource.data.get('deletionRequested', false) != true);`
}
      allow delete: if isOwner() && resource.data.get('deletionRequested', false) == true;`;

  // ── habits, completions, todos, notes ─────────────────────────────────────────────────────────────────────────────────
  const habitValidation = `      // ── Part B: habits and completions ─────────────────────────────────────────────────────────────────────────────────
      // Bounds are generous on purpose: Android has no length limit when a habit is created ("Names have no limit when created"), and an
      // update validates the whole resulting document, so a bound tighter than real stored data would block ordinary check-ins.
      function dateKey(s) { return s is string && s.matches('[0-9]{4}-[0-9]{2}-[0-9]{2}'); }
      function validHabit(d) {
        return d.keys().size() <= 40
          && (!('name' in d) || (d.name is string && d.name.size() >= 1 && d.name.size() <= 1000))
          && (!('goal' in d) || (d.goal is string && d.goal.size() <= 1000))
          && (!('why' in d) || (d.why is string && d.why.size() <= 1000))
          && (!('daysPerWeek' in d) || (d.daysPerWeek is int && d.daysPerWeek >= 1 && d.daysPerWeek <= 7))
          && (!('restDays' in d) || (d.restDays is list && d.restDays.size() <= 7))
          && (!('createdDate' in d) || dateKey(d.createdDate))
          && (!('completedDates' in d) || (d.completedDates is list && d.completedDates.size() <= 20000))
          && (!('scheduleHistory' in d) || (d.scheduleHistory is list && d.scheduleHistory.size() <= 2000))
          && (!('archived' in d) || d.archived is bool)
          && (!('reminderEnabled' in d) || d.reminderEnabled is bool)
          && (!('reminderTime' in d) || d.reminderTime == null || (d.reminderTime is string && d.reminderTime.matches('([01][0-9]|2[0-3]):[0-5][0-9]')))
          && (!('streak' in d) || d.streak is number)
          && (!('bestStreak' in d) || d.bestStreak is number)
          && (!('sortOrder' in d) || d.sortOrder is number)
          && (!('color' in d) || d.color is number)
          && (!('rewardsIgnoredThrough' in d) || dateKey(d.rewardsIgnoredThrough))
          && (!('migratedFrom' in d) || (d.migratedFrom is string && d.migratedFrom.size() <= 200));
      }
      // Timestamp fields (createdAt, updatedAt, completedAt, uncheckedAt) are deliberately NOT type-checked: they carry no business or wallet meaning,
      // and the stored types cannot be inspected with Console queries, so a check would only add a way for ordinary updates of old data to fail.
      function validCompletion(d, date) {
        // Required: completed (every Android and Web write includes it). Allowed: any additional fields, at most 10 in all (the five known ones are
        // date, completed, updatedAt, completedAt, uncheckedAt). An unknown field must never make a stored day impossible to check again.
        return d.keys().size() <= 10
          && 'completed' in d && d.completed is bool
          && (!('date' in d) || d.date == date);
      }

      // Only \`habits/{id}\` and \`habits/{id}/completions/{date}\` exist; any other nested path is refused (it was open before).
      match /habits/{habitId} {
        allow read, delete: if isOwner();
        allow create, update: if isOwner() && validHabit(request.resource.data);
        match /completions/{date} {
          allow read, delete: if isOwner();
          allow create, update: if isOwner() && dateKey(date) && validCompletion(request.resource.data, date);
        }
      }`;
  const habitPathsOnly = `      // Part A: nothing may be created below a habit except \`completions\` (the catch-all \`{rest=**}\` that allowed any nested path is gone).
      // Habits and completions themselves are NOT validated here: a stored document is never re-checked by Part A.
      match /habits/{habitId} {
        allow read, write: if isOwner();
        match /completions/{date} {
          allow read, write: if isOwner();
        }
      }`;
  const habitCurrent = `      match /habits/{habitId}/{rest=**} {
        allow read, write: if isOwner();
      }
      match /habits/{habitId} {
        allow read, write: if isOwner();
      }`;
  const habits = b ? habitValidation : a ? habitPathsOnly : habitCurrent;

  const todos = a
    ? `      // The removed Daily To-Do: Android still deletes these documents when an account is deleted, nothing writes them any more.
      match /todos/{todoId} {
        allow read, delete: if isOwner();
      }`
    : `      match /todos/{todoId} {
        allow read, write: if isOwner();
      }`;

  const dayNotes = b
    ? `      // Optional day notes: one per habit and date (id "{habitId}_{date}"), plain text up to 200 characters. Part B also fixes the date format
      // and allows at most 10 fields (the five known ones are habitId, date, text, createdAt, updatedAt; extra fields are tolerated).
      match /dayNotes/{noteId} {
        allow read, delete: if isOwner();
        allow create, update: if isOwner()
          && noteId == request.resource.data.habitId + '_' + request.resource.data.date
          && dateKey(request.resource.data.date)
          && request.resource.data.keys().size() <= 10
          && request.resource.data.habitId is string
          && request.resource.data.text is string
          && request.resource.data.text.size() > 0
          && request.resource.data.text.size() <= 200;
      }`
    : `      // Optional day notes: one per habit and date (id "{habitId}_{date}"), plain text up to 200 characters.
      // Reflection only; they have no wallet or streak fields and no rule above reads them.
      match /dayNotes/{noteId} {
        allow read, delete: if isOwner();
        allow create, update: if isOwner()
          && noteId == request.resource.data.habitId + '_' + request.resource.data.date
          && request.resource.data.text is string
          && request.resource.data.text.size() > 0
          && request.resource.data.text.size() <= 200;
      }`;

  // ── Part A: the wallet ledger ─────────────────────────────────────────────────────────────────────────────────────────
  const ledgerA = `      // ── Part A: wallet ledger ───────────────────────────────────────────────────────────────────────────────────────────
      // Entries are append-only and must be the entry the wallet update in the same transaction points to, and must also have the shape of an
      // entry the current Android app or the Web can write. Amounts mirror the reward rules (daily 1; milestones 5, 10, 20; price 20) and are
      // validated per type. Whether a reward was EARNED cannot be checked here.
      function entryShape(id) {
        let d = request.resource.data;
        let pd = d.get('pendingDelta', 0);
        return d.keys().hasOnly(['type', 'coinDelta', 'freezeDelta', 'balanceAfter', 'createdAt', 'date', 'habitId', 'milestone', 'pendingDelta', 'rewardId'])
          && d.coinDelta is int && d.freezeDelta is int && d.balanceAfter is int && pd is int
          && (
            (d.type == 'daily_completion' && id.matches('daily_[0-9]{4}-[0-9]{2}-[0-9]{2}')
              && d.freezeDelta == 0 && d.coinDelta >= 0 && pd <= 0 && d.coinDelta - pd == 1)
            || (d.type == 'streak_milestone' && id.matches('milestone_.+')
              && d.freezeDelta == 0 && d.coinDelta >= 0 && pd <= 0 && (d.coinDelta - pd) in [5, 10, 20])
            || (d.type == 'reward_restored' && id.matches('.+_grant[0-9]+')
              && d.freezeDelta == 0 && d.coinDelta >= 0 && pd <= 0 && (d.coinDelta - pd) in [1, 5, 10, 20])
            || (d.type == 'reward_reversal' && id.matches('.+_rev[0-9]+')
              && d.freezeDelta == 0 && d.coinDelta <= 0 && pd >= 0 && (pd - d.coinDelta) in [1, 5, 10, 20])
            || (d.type == 'welcome_freeze' && id == 'welcome_freeze'
              && d.coinDelta == 0 && d.freezeDelta == 1 && pd == 0)
            // The price is exactly 20 coins (FREEZE_PRICE_COINS), one freeze, no pending change.
            || (d.type == 'freeze_purchase' && id.matches('freeze_buy_.+')
              && d.freezeDelta == 1 && d.coinDelta == -20 && pd == 0)
            // An application uses exactly one owned freeze (so freezesOwned must have been at least 1) and spends no coins.
            || (d.type == 'freeze_application' && id.matches('freeze_apply_.+')
              && d.coinDelta == 0 && d.freezeDelta == -1 && pd == 0
              // The freeze record must be written in the same commit.
              && existsAfter(freezePath(id[13:id.size()])))
          );
      }

      match /walletTransactions/{txId} {
        allow read: if isOwner();
        allow create: if isOwner()
          && getAfter(userPath()).data.lastTransactionId == txId
          && entryShape(txId);
        allow update: if false;
        allow delete: if isOwner() && deleting();
      }

      // Reward state (in effect or reversed, and its cycle), written only together with the ledger entry it records.
      match /rewards/{rewardId} {
        allow read: if isOwner();
        allow create, update: if isOwner()
          && request.resource.data.lastTransactionId == getAfter(userPath()).data.lastTransactionId
          && existsAfter(txPath(request.resource.data.lastTransactionId))
          && request.resource.data.keys().hasOnly(['active', 'cycle', 'amount', 'type', 'lastTransactionId', 'updatedAt', 'date', 'habitId', 'milestone'])
          && request.resource.data.active is bool
          && request.resource.data.cycle is int && request.resource.data.cycle >= 1
          && request.resource.data.amount in [1, 5, 10, 20]
          && request.resource.data.type in ['daily_completion', 'streak_milestone'];
        allow delete: if isOwner() && deleting();
      }

      // One freeze per habit per day, created only alongside its ledger entry AND the month counter going up by exactly one.
      match /freezes/{freezeId} {
        allow read: if isOwner();
        allow create: if isOwner()
          && freezeId == request.resource.data.habitId + '_' + request.resource.data.date
          && request.resource.data.keys().hasOnly(['habitId', 'date', 'month', 'paidWith', 'transactionId', 'createdAt'])
          && request.resource.data.date.matches('[0-9]{4}-[0-9]{2}-[0-9]{2}')
          && request.resource.data.month == request.resource.data.date[0:7]
          && existsAfter(txPath('freeze_apply_' + freezeId))
          && getAfter(monthPath(request.resource.data.month)).data.count
            == (exists(monthPath(request.resource.data.month)) ? get(monthPath(request.resource.data.month)).data.count : 0) + 1;
        allow update: if false;
        allow delete: if isOwner() && deleting();
      }

      // Monthly application counter: can only go up by one, never past 3.
      match /freezeMonths/{month} {
        allow read: if isOwner();
        allow create, update: if isOwner()
          && month.matches('[0-9]{4}-[0-9]{2}')
          && request.resource.data.count == (resource == null ? 0 : resource.data.count) + 1
          && request.resource.data.count <= 3;
        allow delete: if isOwner() && deleting();
      }`;
  const ledgerCurrent = `      // Ledger entries are append-only and must be the entry the wallet update in the same transaction points to.
      match /walletTransactions/{txId} {
        allow read: if isOwner();
        allow create: if isOwner()
          && getAfter(userPath()).data.lastTransactionId == txId
          // Rewards (+1 daily, up to +20 for a streak milestone), reward reversals and partial grants (part paid toward
          // a pending adjustment), freeze purchases (-20; earlier ones were -10) and the welcome freeze (0 coins, +1 freeze).
          && request.resource.data.coinDelta is int
          && request.resource.data.coinDelta >= -20 && request.resource.data.coinDelta <= 20
          && request.resource.data.get('pendingDelta', 0) is int
          && request.resource.data.get('pendingDelta', 0) >= -20 && request.resource.data.get('pendingDelta', 0) <= 20
          && request.resource.data.freezeDelta in [0, 1, -1];
        allow update: if false;
        allow delete: if isOwner() && deleting();
      }

      // Reward state (in effect or reversed, and its cycle), written only together with the ledger entry it records.
      match /rewards/{rewardId} {
        allow read: if isOwner();
        allow create, update: if isOwner()
          && request.resource.data.lastTransactionId == getAfter(userPath()).data.lastTransactionId
          && existsAfter(txPath(request.resource.data.lastTransactionId))
          && request.resource.data.active is bool;
        allow delete: if isOwner() && deleting();
      }

      // One freeze per habit per day, created only alongside its ledger entry.
      match /freezes/{freezeId} {
        allow read: if isOwner();
        allow create: if isOwner()
          && freezeId == request.resource.data.habitId + '_' + request.resource.data.date
          && existsAfter(txPath('freeze_apply_' + freezeId));
        allow update: if false;
        allow delete: if isOwner() && deleting();
      }

      // Monthly application counter: can only go up by one, never past 3.
      match /freezeMonths/{month} {
        allow read: if isOwner();
        allow create, update: if isOwner()
          && request.resource.data.count == (resource == null ? 0 : resource.data.count) + 1
          && request.resource.data.count <= 3;
        allow delete: if isOwner() && deleting();
      }`;
  const ledger = a ? ledgerA : ledgerCurrent;

  return `rules_version = '2';

${head}
service cloud.firestore {
  match /databases/{database}/documents {

    match /users/{userId} {
${usersHelpers}

${habits}

${todos}

${dayNotes}

${ledger}
    }

${feedbackSection}
  }
}
`;
}

export const OUTPUTS = [
  { path: 'firebase/firestore.rules', opts: { a: true, b: false } },
  { path: 'firebase/rules/part-b.rules', opts: { a: false, b: true } },
  { path: 'firebase/rules/combined.rules', opts: { a: true, b: true } },
];

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].replace(/\\/g, '/').split('/').pop())) {
  const check = process.argv.includes('--check');
  let bad = 0;
  for (const o of OUTPUTS) {
    const file = join(root, o.path);
    const text = buildRules(o.opts);
    if (check) {
      if (!existsSync(file) || readFileSync(file, 'utf8') !== text) { console.error(`DIFFERS: ${o.path} (run: node scripts/build-rules.mjs)`); bad++; }
    } else {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, text);
      console.log(`wrote ${o.path}`);
    }
  }
  process.exit(bad ? 1 : 0);
}
